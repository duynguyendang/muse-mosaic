"""Olist Brazilian E-Commerce end-to-end test on real data.

Spins an isolated stack (scratch policy dir = repo policies + the Olist
user policy, real trust-engine + real matching engine, temp ledger) and
runs the frozen Olist sample (data/olist/sample_olist.json, generated by
scripts/olist_brazilian_sample.py from the official olist/work-at-olist-data
mirror) through POST /build.

What this proves on real data:
  - the pipeline ingests verbatim third-party values without inventing any;
  - exact order_id hops verify through L1 (sole proof);
  - the zip-only trap neighbour is never merged;
  - every published value traces to a source fact (ledger-backed proof).
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TE_DIR = ROOT / "trust-engine"
SAMPLE = ROOT / "data" / "olist" / "sample_olist.json"


def _free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def _wait_for_port(port: int, timeout: float = 60.0) -> None:
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=1):
                return
        except OSError:
            time.sleep(0.2)
    raise RuntimeError(f"service did not start on {port}")


@pytest.fixture(scope="module")
def olist_stack(tmp_path_factory, trust_engine_binary, mkit_bin, matching_engine):
    """Isolated runtime: scratch policies (repo + Olist), scratch ledger."""
    tmp = tmp_path_factory.mktemp("olist")
    pol_dir = tmp / "policies"
    for entity in ("user", "product"):
        dest = pol_dir / entity
        dest.mkdir(parents=True)
        for path in (TE_DIR / "policies" / entity).glob("*.json"):
            shutil.copy(path, dest / path.name)
        for path in (TE_DIR / "policies" / entity).glob("*.mg"):
            shutil.copy(path, dest / path.name)
    for path in (ROOT / "data" / "olist" / "policies" / "user").glob("*"):
        shutil.copy(path, pol_dir / "user" / path.name)
    tax_dir = tmp / "taxonomy"
    shutil.copytree(ROOT / "data" / "mock" / "taxonomy", tax_dir)

    te_port = _free_port()
    te_env = dict(
        os.environ,
        MANGLEKIT_BIN=str(mkit_bin),
        PORT=str(te_port),
        POLICY_DIR=str(pol_dir),
        TAXONOMY_DIR=str(tax_dir),
    )
    te_proc = subprocess.Popen(
        [str(trust_engine_binary)], env=te_env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
    )
    _wait_for_port(te_port)
    try:
        from conftest import make_api_client

        old_policy, old_tax = os.environ.get("POLICY_DIR"), os.environ.get("TAXONOMY_DIR")
        os.environ["POLICY_DIR"] = str(pol_dir)
        os.environ["TAXONOMY_DIR"] = str(tax_dir)
        try:
            with make_api_client(
                f"http://127.0.0.1:{te_port}/derive",
                tmp,
                matching_service_url=matching_engine,
            ) as client:
                yield client
        finally:
            if old_policy is None:
                os.environ.pop("POLICY_DIR", None)
            else:
                os.environ["POLICY_DIR"] = old_policy
            if old_tax is None:
                os.environ.pop("TAXONOMY_DIR", None)
            else:
                os.environ["TAXONOMY_DIR"] = old_tax
    finally:
        te_proc.terminate()
        try:
            te_proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            te_proc.kill()


def _sample_documents():
    payload = json.loads(SAMPLE.read_text(encoding="utf-8"))
    return payload["documents"]


def _sample_meta():
    import json

    payload = json.loads(
        (ROOT / "data" / "olist" / "sample_olist.json").read_text(encoding="utf-8")
    )
    return payload


# The repo default expected-structure requires an `email` field (hidden
# fixtures always carry one). Olist rows carry no email address, so the
# Olist builds declare their own expected structure: the person key
# customer_unique_id is required, everything else may escalate per-attribute.
OLIST_EXPECTED_STRUCTURE = {
    "type": "object",
    "required": ["customer_unique_id"],
    "properties": {
        "customer_unique_id": {"type": "string", "minLength": 1},
        "customer_zip": {"type": "string"},
        "customer_city": {"type": "string"},
        "customer_state": {"type": "string"},
    },
    "additionalProperties": True,
}


def test_olist_build_publishes_with_proof(olist_stack):
    body = {
        "work_id": "work-olist-1",
        "idempotency_key": "olist-1",
        "dataset": {"documents": _sample_documents()},
        "expected_structure": OLIST_EXPECTED_STRUCTURE,
    }
    response = olist_stack.post("/build", json=body)
    assert response.status_code == 200, response.text
    payload = response.json()
    assert payload["verdict"] in ("published", "escalated")
    goldens = [g for g in payload.get("goldens", []) if g.get("golden_id")]
    assert goldens, "expected at least one published golden on real Olist data"

    # Every published value must be verbatim from the source CSVs.
    import csv

    raw_values = set()
    for name in (
        "olist_customers_dataset.csv",
        "olist_orders_dataset.csv",
        "olist_order_items_dataset.csv",
        "olist_products_dataset.csv",
        "olist_sellers_dataset.csv",
    ):
        path = Path("/tmp/opencode/olist") / name
        if not path.exists():
            continue
        with open(path, newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                raw_values.update(v for v in row.values() if v)
    for golden in goldens:
        for attr, field in (golden.get("attributes") or {}).items():
            value = field.get("value") if isinstance(field, dict) else field
            assert str(value) in raw_values, f"invented value for {attr}: {value!r}"

    # At least one golden attribute must be an engine derivation (R1
    # authority win with ledger lineage), not an unevaluated echo.
    assert any(
        isinstance(field, dict) and field.get("rule_fired") == "R1" and field.get("lineage")
        for golden in goldens
        for field in (golden.get("attributes") or {}).values()
    ), "expected at least one R1-derived attribute with lineage"


def test_olist_trap_neighbour_never_merged(olist_stack):
    body = {
        "work_id": "work-olist-2",
        "idempotency_key": "olist-2",
        "dataset": {"documents": _sample_documents()},
        "expected_structure": OLIST_EXPECTED_STRUCTURE,
    }
    payload = olist_stack.post("/build", json=body).json()
    meta = _sample_meta()["meta"]
    trap_docs = {doc["document_id"] for doc in _sample_documents() if doc.get("trap")}
    assert trap_docs, "sample must contain the trap documents"
    mains = set(meta["main_unique_ids"])
    main_goldens = []
    for golden in payload.get("goldens", []):
        if not golden.get("golden_id"):
            continue
        unique_winner = (golden.get("attributes") or {}).get("customer_unique_id", {})
        unique_value = (
            unique_winner.get("value") if isinstance(unique_winner, dict) else unique_winner
        )
        if unique_value in mains:
            main_goldens.append(golden)
    assert main_goldens, "expected the main person cluster to publish"
    for golden in main_goldens:
        for _name, field in golden["attributes"].items():
            if isinstance(field, dict):
                assert not any(
                    doc in (field.get("winner_fact_id") or "") for doc in trap_docs
                ), "trap fact must never win in the main cluster"
    # The trap cluster stays separate: trap-doc winners may only appear
    # in a golden whose unique_id is the trap customer itself (its own
    # cluster), never merged into a main-cluster golden.
    for golden in payload.get("goldens", []) or []:
        if not golden.get("golden_id"):
            continue
        winner_trap_docs = {
            doc
            for _name, field in (golden.get("attributes") or {}).items()
            if isinstance(field, dict)
            for doc in trap_docs
            if doc and doc in (field.get("winner_fact_id") or "")
        }
        if winner_trap_docs:
            unique_winner = (golden.get("attributes") or {}).get("customer_unique_id", {})
            unique_value = (
                unique_winner.get("value") if isinstance(unique_winner, dict) else unique_winner
            )
            assert (
                unique_value == meta["trap_unique_id"]
            ), f"trap facts verified outside the trap cluster: {winner_trap_docs}"


def test_olist_proposals_carry_real_links(olist_stack):
    body = {
        "work_id": "work-olist-3",
        "idempotency_key": "olist-3",
        "dataset": {"documents": _sample_documents()},
        "expected_structure": OLIST_EXPECTED_STRUCTURE,
    }
    payload = olist_stack.post("/build", json=body).json()
    assert payload.get("proposals"), "expected proposer bundles in the response"
    # At least one sole-proof link (exact order_id shared by an order doc
    # and its item doc) must be proposed: this is what the engine verifies
    # under L1 instead of guessing.
    proofs = {
        link.get("proof")
        for proposal in payload["proposals"]
        for link in (proposal.get("links") or [])
    }
    assert proofs & {
        "exact_order",
        "exact_email",
        "exact_phone",
    }, f"expected a sole-proof link in proposals, got: {sorted(p for p in proofs if p)}"
